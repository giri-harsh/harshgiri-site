// kb/*.md  →  src/kb.js  (read by the browser agent and by api/ask.js)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = path.join(root, "kb");
const docs = fs.readdirSync(dir).filter((f) => f.endsWith(".md") && f !== "README.md").sort().map((f) => {
  const raw = fs.readFileSync(path.join(dir, f), "utf8").replace(/\r\n/g, "\n");
  const m = raw.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
  if (!m) throw new Error(`${f}: missing front matter`);
  const meta = Object.fromEntries(m[1].split("\n").filter(Boolean).map((l) => { const i = l.indexOf(":"); return [l.slice(0, i).trim(), l.slice(i + 1).trim()]; }));
  for (const k of ["id", "src", "title"]) if (!meta[k]) throw new Error(`${f}: front matter needs "${k}"`);
  return { id: meta.id, src: meta.src, title: meta.title, text: m[2].trim().replace(/\s+/g, " "), tags: meta.tags || "" };
});
const ids = new Set();
for (const d of docs) { if (ids.has(d.id)) throw new Error(`duplicate id "${d.id}"`); ids.add(d.id); }
const out = `// GENERATED by scripts/kb.mjs from kb/*.md — edit the markdown, then run \`npm run kb\`.\nglobalThis.KB = ${JSON.stringify(docs, null, 1)};\n`;
const file = path.join(root, "src", "kb.js");
if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== out) fs.writeFileSync(file, out);
console.log(`kb: ${docs.length} documents → src/kb.js`);
